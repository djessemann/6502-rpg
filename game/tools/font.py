"""The resident text/UI CHR bank (BG tiles $00-$3F, MMC3 CHR reg R2).

64 tiles, always resident:
    $00        blank (also the space glyph and the box-interior tile)
    $01-$34    the 52 printable glyphs of CHARSET[1:]
    $35        DOWN ARROW  ("more text" prompt)
    $36        CURSOR      (menu pointer)
    $37-$3F    the 9 window-frame tiles (TL T TR L C R BL B BR)

Glyphs are 5x7, drawn at x=1..5 / y=0..6 inside the 8x8 tile, in colour 3.
The frame is drawn in colour 1.
"""
from chrlib import tile_from_rows

CHARSET = " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789.,!?'\"-:;/()%+=*"

TILE_BLANK = 0x00
TILE_ARROW = 0x35
TILE_CURSOR = 0x36
TILE_FRAME = 0x37          # +0..8 = TL T TR L C R BL B BR

