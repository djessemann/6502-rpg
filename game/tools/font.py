def build_font_bank():
    """Return the 64 tiles of the resident text/UI bank."""
    tiles = []
    for ch in CHARSET:
        if ch == ' ':
            tiles.append(tile_from_rows(["........"] * 8))
        else:
            tiles.append(_glyph_tile(GLYPHS[ch]))
    assert len(tiles) == 53, len(tiles)
    tiles.append(_glyph_tile(ARROW))    # $35
    tiles.append(_glyph_tile(CURSOR))   # $36
    for art in FRAME_ART:               # $37..$3F
        tiles.append(tile_from_rows(art))
    assert len(tiles) == 64, len(tiles)
    return tiles


_INDEX = {c: i for i, c in enumerate(CHARSET)}


def encode(s):
    """Map a string to font tile indices. Unknown chars raise."""
    out = []
    for ch in s:
        i = _INDEX.get(ch.upper() if ch.isalpha() else ch)
        if i is None:
            raise ValueError(f"character {ch!r} is not in CHARSET (in {s!r})")
        out.append(i)
    return out
