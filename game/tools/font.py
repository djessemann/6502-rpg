CURSOR = (0x08, 0x0C, 0x0E, 0x0F, 0x0E, 0x0C, 0x08)


def _glyph_tile(bits, colour='3'):
    rows = []
    for i in range(7):
        b = bits[i]
        line = ['.'] * 8
        for x in range(5):
            if b & (0x10 >> x):
                line[1 + x] = colour
        rows.append("".join(line))
    rows.append("." * 8)
    return tile_from_rows(rows)


