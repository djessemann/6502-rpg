def to_digits(art):
    """Convert '#'/'.' art into the digit strings to_chr() expects (1=white)."""
    return ["".join("1" if c == "#" else "0" for c in row) for row in art]


# Glyphs that already have 1px-gap vertical strokes (combs); right-dilation
# would blob them, so they are authored pre-thickened and skip the pass.
BOLD_EXEMPT = set("mwMW")


def thicken(art):
    """Faux-bold: extend each stroke one pixel to the right (2px stems)."""
    out = []
    for row in art:
        new = list(row)
        for j in range(1, len(row)):
            if row[j] == "." and row[j - 1] == "#":
                new[j] = "#"
        out.append("".join(new))
    return out


def glyph(ch):
    """Font tile: '#' = white ink (value 1) on '.' = black (value 0)."""
    art = FONT[ch]
    if ch not in BOLD_EXEMPT:
        art = thicken(art)
    return to_digits(art)


def wrap_text(text, width):
    """Greedy word-wrap into a list of lines no wider than `width`."""
    lines, cur = [], ""
    for word in text.split():
        assert len(word) <= width, f"word too long: {word!r}"
        if not cur:
            cur = word
        elif len(cur) + 1 + len(word) <= width:
            cur += " " + word
        else:
            lines.append(cur)
            cur = word
    if cur:
        lines.append(cur)
    return lines


def encode_message(text, font_id):
    """Wrap + paginate `text` into the runtime byte stream (see MESSAGES).
    A form-feed ("\\f") in the source forces a page break."""
    pages = []
    for segment in text.split("\f"):
        lines = wrap_text(segment, TEXT_W)
        for p in range(0, max(len(lines), 1), TEXT_H):
            pages.append(lines[p:p + TEXT_H])

    out = []
    for pi, page in enumerate(pages):
        page = list(page) + [""] * (TEXT_H - len(page))   # pad to 4 lines
        last_page = pi == len(pages) - 1
        for i, line in enumerate(page):
            for ch in line:
                out.append(0x00 if ch == " " else font_id[ch])
            if i < TEXT_H - 1:
                out.append(MSG_NEWLINE)
            else:
                out.append(MSG_END if last_page else MSG_PAGE)
    return out


