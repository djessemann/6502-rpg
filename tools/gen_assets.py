def to_chr(rows):
    """Encode one 8x8 tile (rows of digit chars) to 16 planar bytes."""
    p0, p1 = [], []
    for row in rows:
        b0 = b1 = 0
        for px in row:
            v = int(px)
            b0 = (b0 << 1) | (v & 1)
            b1 = (b1 << 1) | ((v >> 1) & 1)
        p0.append(b0)
        p1.append(b1)
    return p0 + p1


def split16(block):
    """Split a 16x16 art block into 4 8x8 tiles ordered TL, TR, BL, BR."""
    return [
        [r[0:8] for r in block[0:8]],
        [r[8:16] for r in block[0:8]],
        [r[0:8] for r in block[8:16]],
        [r[8:16] for r in block[8:16]],
    ]


def mirror_h(block):
    """Horizontally mirror an art block (used to make a left-facing BG view)."""
    return [row[::-1] for row in block]


def mirror_v(block):
    """Vertically mirror an art block."""
    return block[::-1]


def double(block):
    """2x-scale an NxN art block (each pixel becomes 2x2)."""
    out = []
    for row in block:
        big = "".join(c * 2 for c in row)
        out.append(big)
        out.append(big)
    return out


def split_grid(block, n):
    """Split an (8n)x(8n) art block into n*n 8x8 tiles, row-major."""
    tiles = []
    for tr in range(n):
        for tc in range(n):
            tiles.append([r[tc * 8:(tc + 1) * 8] for r in block[tr * 8:(tr + 1) * 8]])
    return tiles


