def to_digits(art):
    """Convert '#'/'.' art into the digit strings to_chr() expects (1=white)."""
    return ["".join("1" if c == "#" else "0" for c in row) for row in art]


def glyph(ch):
    """Font tile: '#' = white ink (value 1) on '.' = black (value 0)."""
    return to_digits(FONT[ch])


def main():
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    src = os.path.join(here, "src")

    # --- assemble the ordered background tile table ---
    font_chars = sorted(FONT.keys())
    font_id = {ch: F_BASE + i for i, ch in enumerate(font_chars)}

    bg = {}
    bg.update(TILES)
    # NPC four facings (left is mirrored from the right-facing "side" art).
    npc_blocks = {
        NPC_DOWN: NPC_VIEWS["down"],
        NPC_UP: NPC_VIEWS["up"],
        NPC_RIGHT: NPC_VIEWS["side"],
        NPC_LEFT: mirror_h(NPC_VIEWS["side"]),
    }
    for base, block in npc_blocks.items():
        for i, tile in enumerate(split16(block)):
            bg[base + i] = tile
    # Window frame: author TL + top/left edges + fill; mirror for the rest.
    tl = to_digits(WIN_TL_ART)
    top = to_digits(WIN_T_ART)
    left = to_digits(WIN_L_ART)
    bg[W_TL] = tl
    bg[W_T] = top
    bg[W_TR] = mirror_h(tl)
    bg[W_L] = left
    bg[W_FILL] = to_digits(WIN_FILL_ART)
    bg[W_R] = mirror_h(left)
    bg[W_BL] = mirror_v(tl)
    bg[W_B] = mirror_v(top)
    bg[W_BR] = mirror_v(mirror_h(tl))
    for ch in font_chars:
        bg[font_id[ch]] = glyph(ch)
    e_base = F_BASE + len(font_chars)          # enemy tiles follow the font
    for i, tile in enumerate(split_grid(double(ENEMY16), 4)):
        bg[e_base + i] = tile

    last_bg = max(bg)
    bg_bytes = []
    for tid in range(last_bg + 1):
        bg_bytes += to_chr(bg.get(tid, ["00000000"] * 8))

    # Hero sprite tiles: down, up, side (left = side H-flipped at draw time).
    hero_bytes = []
    for view in ("down", "up", "side"):
        for tile in split16(HERO_VIEWS[view]):
            hero_bytes += to_chr(tile)

    with open(os.path.join(src, "chr.s"), "w") as f:
        f.write("; chr.s - GENERATED by tools/gen_assets.py. Do not edit by hand.\n")
        f.write("; Pattern table 0: field tiles, NPC (4 facings), window, font, enemy ($00-$%02X).\n" % last_bg)
        f.write("; Pattern table 1 ($1000): hero tiles - down $00, up $04, side $08.\n")
        f.write("; The CHR region fills the remaining 8KB with zero (see nes.cfg).\n\n")
        f.write('.segment "CHARS"\n')
        f.write("    ; --- pattern table 0: background ---\n")
        for i in range(0, len(bg_bytes), 16):
            row = ", ".join(f"${b:02X}" for b in bg_bytes[i:i + 16])
            f.write(f"    .byte {row}   ; bg tile ${i // 16:02X}\n")
        pad = 0x1000 - len(bg_bytes)
        f.write(f"\n    .res ${pad:04X}, $00   ; pad to pattern table 1 ($1000)\n\n")
        f.write("    ; --- pattern table 1: sprites ---\n")
        for i in range(0, len(hero_bytes), 16):
            row = ", ".join(f"${b:02X}" for b in hero_bytes[i:i + 16])
            f.write(f"    .byte {row}   ; hero tile ${i // 16:02X}\n")

    # --- build the field map ---
    W, H = 32, 30
    m = [[T_GRASS] * W for _ in range(H)]
    for x in range(W):
        m[0][x] = T_TREE
        m[H - 1][x] = T_TREE
    for y in range(H):
        m[y][0] = T_TREE
        m[y][W - 1] = T_TREE
    for y in range(3, 8):
        for x in range(3, 9):
            m[y][x] = T_WATER
    for y in range(1, H - 1):
        m[y][16] = T_PATH
    for x in range(1, W - 1):
        m[22][x] = T_PATH
    for x in range(20, 26):
        m[3][x] = T_WALL
        m[7][x] = T_WALL
    for y in range(3, 8):
        m[y][20] = T_WALL
        m[y][25] = T_WALL
    for (x, y) in [(5, 12), (9, 18), (13, 25), (27, 10), (29, 19), (23, 24), (6, 26)]:
        m[y][x] = T_FLOWER
    for (x, y) in [(11, 11), (28, 6), (4, 20), (19, 27), (26, 14), (8, 9)]:
        m[y][x] = T_BUSH

    # stamp the NPC (2x2 background tiles) at its grid cell, in its facing
    npc_base = NPC_FACE[NPC_FACING]
    bx, by = NPC_GX * 2, NPC_GY * 2
    m[by][bx], m[by][bx + 1] = npc_base + 0, npc_base + 1
    m[by + 1][bx], m[by + 1][bx + 1] = npc_base + 2, npc_base + 3

    def palette_of(tile):
        if tile == T_WATER:
            return 1
        if NPC_DOWN <= tile <= NPC_RIGHT + 3:   # any NPC facing tile
            return 2
        return 0

    def attr_table(grid):
        attr = [0] * 64
        for ay in range(8):
            for ax in range(8):
                byte = 0
                for q in range(4):
                    qx, qy = q & 1, q >> 1
                    pal = 0
                    for ty in range(2):
                        for tx in range(2):
                            x = ax * 4 + qx * 2 + tx
                            y = ay * 4 + qy * 2 + ty
                            if 0 <= y < H and 0 <= x < W:
                                pal = max(pal, palette_of(grid[y][x]))
                    byte |= pal << (q * 2)
                attr[ay * 8 + ax] = byte
        return attr

    flat = [m[y][x] for y in range(H) for x in range(W)]
    attr = attr_table(m)

    # --- build the large bottom window tilemap: 32 wide x 8 tall ---
    # Full screen width (so the palette-3 attribute band aligns cleanly), with a
    # 1-tile black margin (W_FILL) inside the edges, the double-line frame, and
    # a 28x5 text interior. Drawn at nametable rows 20-27.
    IN_W, IN_H = 28, 5
    lines = (list(SAMPLE_LINES) + [""] * IN_H)[:IN_H]

    def interior_row(s):
        cells = [W_FILL if c == " " else font_id[c] for c in s[:IN_W]]
        cells += [W_FILL] * (IN_W - len(cells))
        return [W_FILL, W_L] + cells + [W_R, W_FILL]

    winmap = [W_FILL] * 32                                   # row 0: top margin
    winmap += [W_FILL, W_TL] + [W_T] * IN_W + [W_TR, W_FILL]  # row 1: top frame
    for r in range(IN_H):                                    # rows 2-6: text
        winmap += interior_row(lines[r])
    winmap += [W_FILL, W_BL] + [W_B] * IN_W + [W_BR, W_FILL]  # row 7: bottom

    # window draw steps: 32 tile chunks of 8 + 2 attribute chunks of 8
    win_steps = 32 * 8 // 8 + 2

    with open(os.path.join(src, "field.s"), "w") as f:
        f.write("; field.s - GENERATED by tools/gen_assets.py. Do not edit by hand.\n")
        f.write("; One-screen field map + attribute table, and the text window tilemap.\n\n")
        f.write(".export fieldmap, fieldattr, winmap\n\n")
        f.write('.segment "RODATA"\n')
        f.write(fmt_bytes("fieldmap", flat, 32) + "\n\n")
        f.write(fmt_bytes("fieldattr", attr, 16) + "\n\n")
        f.write(fmt_bytes("winmap", winmap, 32) + "\n")

    # tile-index constants consumed by main.s (so nothing is hardcoded there)
    with open(os.path.join(src, "tiles.inc"), "w") as f:
        f.write("; tiles.inc - GENERATED by tools/gen_assets.py. Do not edit by hand.\n\n")
        f.write("; Sprite tiles (pattern table 1), 4 tiles per facing.\n")
        f.write(f"HERO_DOWN_TILE = ${HERO_DOWN:02X}\n")
        f.write(f"HERO_UP_TILE   = ${HERO_UP:02X}\n")
        f.write(f"HERO_SIDE_TILE = ${HERO_SIDE:02X}\n\n")
        f.write("; Background tiles (pattern table 0).\n")
        f.write(f"TILE_NPC_LO = ${NPC_DOWN:02X}   ; first NPC tile (all facings)\n")
        f.write(f"TILE_NPC_HI = ${NPC_RIGHT + 3:02X}   ; last NPC tile (solid range)\n")
        f.write(f"ENEMY_TILE_BASE = ${e_base:02X}\n\n")
        f.write("; Text window: full-width box at nametable rows 20-27.\n")
        f.write(f"WIN_STEPS = {win_steps}\n")

    # console preview
    glyphs = {T_GRASS: ".", T_FLOWER: ",", T_PATH: ":", T_TREE: "T",
              T_WALL: "#", T_BUSH: "o", T_WATER: "~"}
